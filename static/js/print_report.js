/**
 * Shared "Print PDF" utility for every table-based report page in the app.
 * Clones a table (or an explicit HTML string), wraps it in a formatted
 * print window with a company header/footer, and opens the browser's print
 * dialog — the same clone-and-print technique reports.html's own
 * printReport() established, generalized here so every other report page
 * reuses one implementation instead of each carrying its own near-duplicate
 * copy (which is how the first three of these were built, before this
 * file existed).
 *
 * Usage: printTablePDF('Report Title', document.getElementById('tbl-id'))
 * Optional third argument: { meta: 'extra line under the title',
 * excludeSelector: '.no-print' (columns/cells to strip before printing,
 * e.g. an Actions column) }.
 */
function printTablePDF(title, tableEl, opts) {
    opts = opts || {};
    if (!tableEl) {
        alert('No data to print.');
        return;
    }

    const clone = tableEl.cloneNode(true);
    clone.style.display = '';
    clone.removeAttribute('hidden');

    // Drop anything marked .no-print (action buttons, checkboxes, etc.) —
    // both whole columns (th/td at a given index) and any element with the
    // class directly.
    const noPrintCells = clone.querySelectorAll(opts.excludeSelector || '.no-print');
    noPrintCells.forEach(el => el.remove());

    const companyName = window.APP_COMPANY_NAME || '';
    const companyTagline = window.APP_COMPANY_TAGLINE || '';
    const meta = opts.meta || '';

    const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>${title} — ${companyName}</title>
<style>
  * { box-sizing: border-box; margin: 0; padding: 0; }
  body { font-family: Arial, sans-serif; font-size: 12px; color: #111; background: #fff; }
  @page { margin: 1.2cm; size: A4; }

  .print-header { display: flex; justify-content: space-between; align-items: flex-start;
                  border-bottom: 3px solid #1e3a5f; padding-bottom: 10px; margin-bottom: 16px; }
  .company-block .cname { font-size: 18px; font-weight: 900; color: #1e3a5f; }
  .company-block .ctag  { font-size: 10px; color: #666; }
  .report-block { text-align: right; }
  .report-block .rtitle { font-size: 15px; font-weight: 800; color: #1e3a5f; text-transform: uppercase; letter-spacing: 1px; }
  .report-block .rmeta  { font-size: 10px; color: #555; margin-top: 3px; }
  .print-footer { margin-top: 20px; border-top: 1px solid #ccc; padding-top: 8px;
                  display: flex; justify-content: space-between; font-size: 10px; color: #888; }

  table { width: 100%; border-collapse: collapse; margin-top: 4px; }
  th { background: #1e3a5f; color: white; padding: 6px 8px; text-align: left; font-size: 11px; }
  /* Never fold a number onto a second line. */
  th.text-end, td.text-end,
  th.table-cell-right, td.table-cell-right { text-align: right; white-space: nowrap; }
  th.text-center, td.text-center,
  th.table-cell-center, td.table-cell-center { text-align: center; }
  td { padding: 5px 8px; border-bottom: 1px solid #e5e7eb; font-size: 11px; overflow-wrap: break-word; }
  tfoot td { background: #f3f4f6; font-weight: 700; border-top: 2px solid #9ca3af; }
  tr:nth-child(even) td { background: #f9fafb; }
  .badge-success { color: #166534; background: #dcfce7; padding: 2px 8px; border-radius: 99px; font-size: 10px; }
  .badge-danger, .badge-danger-solid  { color: #991b1b; background: #fee2e2; padding: 2px 8px; border-radius: 99px; font-size: 10px; }
  .badge-warning { color: #92400e; background: #fef3c7; padding: 2px 8px; border-radius: 99px; font-size: 10px; }
  .badge-secondary { color: #374151; background: #e5e7eb; padding: 2px 8px; border-radius: 99px; font-size: 10px; }
</style>
</head>
<body>
<div class="print-header">
  <div class="company-block">
    <div class="cname">&#9633; ${companyName}</div>
    <div class="ctag">${companyTagline}</div>
  </div>
  <div class="report-block">
    <div class="rtitle">${title}</div>
    ${meta ? '<div class="rmeta">' + meta + '</div>' : ''}
  </div>
</div>

${clone.outerHTML}

<div class="print-footer">
  <span>Generated by ${companyName} &mdash; ${companyTagline}</span>
  <span>Printed: ${new Date().toLocaleDateString('en-GB', {day:'2-digit',month:'short',year:'numeric'})}</span>
</div>
</body></html>`;

    const win = window.open('', '_blank', 'width=900,height=700');
    win.document.write(html);
    win.document.close();
    win.focus();
    setTimeout(() => { win.print(); }, 400);
}
